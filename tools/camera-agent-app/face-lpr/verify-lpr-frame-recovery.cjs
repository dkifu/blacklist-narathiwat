'use strict'
// Stage 20: no NVR traffic; tests bounded FFmpeg fallback and input checks.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { decodeFirstJpeg, inspectH264 } = require('./lpr-playback-frame-decode.cjs')
const fixture = fs.readFileSync(path.join(__dirname, 'fixtures', 'synthetic-lpr-test.h264'))
const baseline = decodeFirstJpeg(fixture)
assert.equal(baseline[0], 0xff)
assert.equal(baseline[1], 0xd8)
assert.equal(baseline.at(-2), 0xff)
assert.equal(baseline.at(-1), 0xd9)
assert.ok(inspectH264(fixture).idr >= 1)
console.log('PASS: FFmpeg synthetic H264 decodes to bounded JPEG')
// Simulate a playback stream beginning mid-GOP, before the valid SPS/PPS/IDR.
const garbageP = Buffer.concat([Buffer.from([0,0,0,1,0x41]), Buffer.alloc(500, 0xe7)])
const recovery = decodeFirstJpeg(Buffer.concat([garbageP, fixture]))
assert.equal(recovery[0], 0xff)
assert.equal(recovery.at(-1), 0xd9)
console.log('PASS: non-keyframe prefix does not prevent IDR frame recovery')
assert.throws(() => decodeFirstJpeg(Buffer.from([0,0,0,1,0x41,0,0,0,1,0x09])), /NO_SPS_PPS_IDR/)
assert.throws(() => decodeFirstJpeg(Buffer.alloc(8*1024*1024+1)), /H264_INPUT_INVALID/)
console.log('PASS: missing IDR and oversized H264 rejected')
const { readConfig } = require('./config.cjs')
const config = readConfig(path.join(__dirname, 'pilot.config.json'))
assert.equal(config.enabled, false)
console.log('PASS: pilot remains disabled; decoder never stores media or credentials')
console.log('LPR_FRAME_RECOVERY_OFFLINE_TEST: PASS')
console.log('REAL_NVR_REQUEST_SENT: NO')
console.log('MEDIA_SAVED: NO')
console.log('MAIN_CJS_CHANGED: NO')
